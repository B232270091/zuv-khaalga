import { test, expect } from '@playwright/test';

const snapshot = (page: import('@playwright/test').Page) => page.evaluate(() => (window as any).__gameSnapshot());
test('menu, grades, instructions, sound, keyboard, pause and restart', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/'); await expect(page.locator('canvas')).toBeVisible();
  await expect(page.locator('#render-error')).toBeHidden();
  await page.screenshot({ path: `test-results/${info.project.name}-menu.png`, fullPage: true });
  await page.getByRole('button', { name: 'Заавар', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Яаж тоглох вэ?' })).toBeVisible();
  await page.getByRole('button', { name: 'Ойлголоо' }).click();
  await page.locator('[data-grade="3"]').click(); await expect(page.locator('[data-grade="3"]')).toHaveAttribute('aria-pressed', 'true');
  await page.locator('#sound').click(); await expect(page.locator('#sound')).toHaveAttribute('aria-pressed', 'false');
  await page.locator('#play').click(); await expect(page.locator('#question')).toBeVisible();
  expect((await snapshot(page)).grade).toBe(3);
  await page.keyboard.press('ArrowRight'); expect((await snapshot(page)).lane).toBe(1);
  await page.keyboard.press('a'); expect((await snapshot(page)).lane).toBe(0);
  await page.locator('#right').dispatchEvent('pointerdown', { pointerType: 'touch' }); expect((await snapshot(page)).lane).toBe(1);
  await page.locator('#left').dispatchEvent('pointerdown', { pointerType: 'touch' }); expect((await snapshot(page)).lane).toBe(0);
  await page.locator('#scene-wrap').dispatchEvent('pointerdown', { clientX: 100, clientY: 400, pointerId: 1, pointerType: 'touch' });
  await page.locator('#scene-wrap').dispatchEvent('pointerup', { clientX: 230, clientY: 410, pointerId: 1, pointerType: 'touch' });
  expect((await snapshot(page)).lane).toBe(1);
  await page.keyboard.press('p'); await expect(page.locator('#pause-dialog')).toBeVisible();
  const frozen = await snapshot(page); await page.waitForTimeout(400);
  expect((await snapshot(page)).elapsed).toBe(frozen.elapsed);
  await page.locator('#resume').click(); expect((await snapshot(page)).state).toBe('playing');
  await page.screenshot({ path: `test-results/${info.project.name}-playing.png` });
  await page.keyboard.press('Escape'); await page.locator('#pause-menu').click();
  await expect(page.locator('#menu')).toBeVisible(); await page.locator('#play').click();
  const fresh = await snapshot(page); expect(fresh.score).toBe(0); expect(fresh.multiplier).toBe(1); expect(fresh.elapsed).toBeLessThan(1); expect(fresh.lane).toBe(0);
  expect(errors).toEqual([]);
});

test('correct door, locked input, wrong door, correction, saved record, and automatic pause', async ({ page }, info) => {
  await page.goto('/'); await page.locator('#play').click();
  const initial = await snapshot(page); const first = initial.walls[0];
  await page.keyboard.press(first.question.correctLane === 0 ? 'ArrowLeft' : 'ArrowRight');
  await expect.poll(async () => (await snapshot(page)).locked, { timeout: 15000 }).toBe(true);
  await page.keyboard.press(first.question.correctLane === 0 ? 'ArrowRight' : 'ArrowLeft');
  expect((await snapshot(page)).lane).toBe(first.question.correctLane);
  await expect.poll(async () => (await snapshot(page)).walls[0].open, { timeout: 3000 }).toBe(1);
  await page.screenshot({ path: `test-results/${info.project.name}-open-door.png` });
  await expect.poll(async () => (await snapshot(page)).score, { timeout: 4000 }).toBe(1);
  await page.screenshot({ path: `test-results/${info.project.name}-passed-door.png` });
  const after = await snapshot(page); const second = after.walls.filter((w: any) => !w.scored).sort((a: any, b: any) => a.distance - b.distance)[0];
  expect(second.question).toBeTruthy();
  await page.keyboard.press(second.question.correctLane === 0 ? 'ArrowRight' : 'ArrowLeft');
  await expect.poll(async () => (await snapshot(page)).state, { timeout: 15000 }).toBe('gameover');
  await expect(page.locator('#end-score')).toHaveText('1');
  await expect(page.locator('#correction')).toHaveText(`${second.question.text} = ${second.question.answer}`);
  expect((await snapshot(page)).walls.find((w: any) => w.id === second.id).open).toBe(0);
  await page.screenshot({ path: `test-results/${info.project.name}-result.png` });
  await page.locator('#restart').click(); expect((await snapshot(page)).score).toBe(0);
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await expect(page.locator('#pause-dialog')).toBeVisible();
  await page.locator('#pause-menu').click(); await expect(page.locator('#menu-best')).toHaveText('1');
  await page.reload(); await expect(page.locator('#menu-best')).toHaveText('1');
  const overflows = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  expect(overflows).toBe(false);
});
